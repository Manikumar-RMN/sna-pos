-- 128: Report pack RPCs - popular items, unsold / slow items, waiter-wise sales, discount summary.
--
-- Problem: the four report pages under /reports (popular-items, slow-items, waiter-sales, discounts) read the tables
-- orders / order_items directly. Their row level security (057_multi_outlet.sql) is
--     branch_id = app.current_branch_id()
-- so they only ever saw the CURRENT outlet, even when the person had chosen "All outlets" in the outlet picker.
--
-- Fix: four read-only SECURITY DEFINER functions that follow the outlet picker exactly like sales_report (119) and
-- outlet_comparison (057): the scope comes from app.report_branch() (null = all outlets, only for the owner or a person
-- with no outlet restriction; otherwise the one current outlet). Same rules as the pages they replace:
--   * bills: status 'completed', not merged into another bill, by BUSINESS day (orders.business_date), own restaurant
--   * order lines: not cancelled (cancelled_at is null)
--   * waiter sales and discounts leave out complimentary and staff-meal bills (comp_kind is not null), like the pages did
--   * popular items does NOT leave them out (the page never did: a complimentary dish was still cooked and served)
-- Permissions: all need report.view_sales; the discount summary also needs report.view_financial.
-- Nothing is written. Safe to run again (create or replace).
--
-- Return shapes (jsonb):
--   report_popular_items  -> [ {product_id, name, units, amount} ]                       best seller first, at most 100
--   report_unsold_items   -> {unsold: [{id, name}], sold_least: [{product_id, name, units, amount}]}
--   report_waiter_sales   -> [ {branch_id, outlet_name, user_id, staff_name, bills, covers|null, sales} ]  biggest sales first
--   report_discounts      -> {by_cashier: [{branch_id, outlet_name, user_id, name, bills, total, max_pct}],
--                             by_day: [{business_date, bills, total, max_pct}],
--                             by_outlet: [{branch_id, outlet_name, bills, total, max_pct}]}

create or replace function public.report_popular_items(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v_rest uuid; v_rb uuid;
begin
  perform app.require_permission('report.view_sales');
  if p_from is null or p_to is null or p_to < p_from then raise exception 'Choose a valid date range.'; end if;
  if p_to - p_from > 366 then raise exception 'Choose a range of one year or less.'; end if;
  v_rest := app.current_restaurant_id();
  v_rb   := app.report_branch();      -- null = all outlets; same test as app.in_scope(o.branch_id)
  return coalesce((
    select jsonb_agg(jsonb_build_object('product_id', x.product_id, 'name', x.name, 'units', x.units, 'amount', x.amount)
                     order by x.units desc, x.amount desc, x.name)
      from (
        select oi.product_id,
               min(oi.product_name)                       as name,
               round(sum(oi.quantity), 2)                 as units,
               round(sum(oi.line_subtotal), 2)            as amount
          from public.order_items oi
          join public.orders o on o.id = oi.order_id
         where o.restaurant_id = v_rest
           and (v_rb is null or o.branch_id = v_rb)
           and o.business_date between p_from and p_to
           and o.status = 'completed' and o.merged_into is null
           and oi.cancelled_at is null
         group by oi.product_id, case when oi.product_id is null then oi.product_name end
         order by sum(oi.quantity) desc, sum(oi.line_subtotal) desc, min(oi.product_name)
         limit 100) x
  ), '[]'::jsonb);
end $$;

create or replace function public.report_unsold_items(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v_rest uuid; v_rb uuid;
begin
  perform app.require_permission('report.view_sales');
  if p_from is null or p_to is null or p_to < p_from then raise exception 'Choose a valid date range.'; end if;
  if p_to - p_from > 366 then raise exception 'Choose a range of one year or less.'; end if;
  v_rest := app.current_restaurant_id();
  v_rb   := app.report_branch();

  return (
    with outlets as (
      select b.id from public.branches b
       where b.restaurant_id = v_rest and b.deleted_at is null and app.can_use_branch(b.id)),
    -- Items that can be sold: on the menu, switched on, not an extra charge, not the parent of sizes/variants (the sizes are the items),
    -- and not switched off at the outlet (one outlet), or switched off in EVERY outlet the person can see (all outlets).
    active as (
      select p.id, p.name
        from public.products p
       where p.restaurant_id = v_rest and p.deleted_at is null and p.is_available and not p.is_charge
         and not exists (select 1 from public.products c
                          where c.parent_id = p.id and c.restaurant_id = v_rest and c.deleted_at is null and c.is_available and not c.is_charge)
         and case
               when v_rb is not null then
                 not exists (select 1 from public.branch_prices bp
                              where bp.product_id = p.id and bp.branch_id = v_rb and bp.is_available = false)
               else
                 not (exists (select 1 from outlets)
                      and not exists (select 1 from outlets ol
                                       where not exists (select 1 from public.branch_prices bp
                                                          where bp.product_id = p.id and bp.branch_id = ol.id and bp.is_available = false)))
             end),
    sold as (
      select oi.product_id, min(oi.product_name) as name,
             round(sum(oi.quantity), 2) as units, round(sum(oi.line_subtotal), 2) as amount
        from public.order_items oi
        join public.orders o on o.id = oi.order_id
       where o.restaurant_id = v_rest
         and (v_rb is null or o.branch_id = v_rb)
         and o.business_date between p_from and p_to
         and o.status = 'completed' and o.merged_into is null
         and oi.cancelled_at is null
       group by oi.product_id, case when oi.product_id is null then oi.product_name end)
    select jsonb_build_object(
      'unsold', coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'name', a.name) order by a.name, a.id)
                            from active a where not exists (select 1 from sold s where s.product_id = a.id)), '[]'::jsonb),
      'sold_least', coalesce((select jsonb_agg(jsonb_build_object('product_id', y.product_id, 'name', y.name, 'units', y.units, 'amount', y.amount)
                                               order by y.units, y.amount, y.name)
                                from (select s.product_id, s.name, s.units, s.amount
                                        from sold s
                                       where s.product_id in (select a.id from active a)
                                       order by s.units, s.amount, s.name
                                       limit 20) y), '[]'::jsonb)));
end $$;

create or replace function public.report_waiter_sales(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v_rest uuid; v_rb uuid;
begin
  perform app.require_permission('report.view_sales');
  if p_from is null or p_to is null or p_to < p_from then raise exception 'Choose a valid date range.'; end if;
  if p_to - p_from > 366 then raise exception 'Choose a range of one year or less.'; end if;
  v_rest := app.current_restaurant_id();
  v_rb   := app.report_branch();
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'branch_id', x.branch_id, 'outlet_name', x.outlet_name, 'user_id', x.user_id, 'staff_name', x.staff_name,
             'bills', x.bills, 'covers', x.covers, 'sales', x.sales)
           order by x.sales desc, x.outlet_name, x.user_id)
      from (
        select o.branch_id,
               coalesce(b.name, 'Unknown outlet')                         as outlet_name,
               coalesce(o.waiter_id, o.cashier_id)                        as user_id,
               coalesce(u.full_name, 'Unknown')                           as staff_name,
               count(*)                                                   as bills,
               nullif(sum(greatest(0, trunc(o.covers))), 0)               as covers,
               coalesce(sum(o.grand_total), 0)                            as sales
          from public.orders o
          left join public.branches b on b.id = o.branch_id
          left join public.users u on u.id = coalesce(o.waiter_id, o.cashier_id)
         where o.restaurant_id = v_rest
           and (v_rb is null or o.branch_id = v_rb)
           and o.business_date between p_from and p_to
           and o.status = 'completed' and o.merged_into is null
           and o.comp_kind is null                                         -- no complimentary or staff-meal bills
           and coalesce(o.waiter_id, o.cashier_id) is not null
         group by o.branch_id, b.name, coalesce(o.waiter_id, o.cashier_id), u.full_name) x
  ), '[]'::jsonb);
end $$;

create or replace function public.report_discounts(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v_rest uuid; v_rb uuid;
begin
  perform app.require_permission('report.view_sales');
  if not app.has_permission('report.view_financial') then raise exception 'You do not have the right to see financial reports.'; end if;
  if p_from is null or p_to is null or p_to < p_from then raise exception 'Choose a valid date range.'; end if;
  if p_to - p_from > 366 then raise exception 'Choose a range of one year or less.'; end if;
  v_rest := app.current_restaurant_id();
  v_rb   := app.report_branch();

  return (
    with d as (
      select o.branch_id, o.business_date, o.cashier_id, o.discount_total,
             case when o.subtotal > 0 then round(least(100, o.discount_total / o.subtotal * 100), 2) else 0 end as pct
        from public.orders o
       where o.restaurant_id = v_rest
         and (v_rb is null or o.branch_id = v_rb)
         and o.business_date between p_from and p_to
         and o.status = 'completed' and o.merged_into is null
         and o.comp_kind is null                      -- no complimentary or staff-meal bills
         and o.discount_total > 0)
    select jsonb_build_object(
      'by_cashier', coalesce((
          select jsonb_agg(jsonb_build_object('branch_id', x.branch_id, 'outlet_name', x.outlet_name, 'user_id', x.user_id,
                   'name', x.name, 'bills', x.bills, 'total', x.total, 'max_pct', x.max_pct) order by x.total desc, x.name, x.user_id)
            from (select dd.branch_id, coalesce(b.name, 'Unknown outlet') as outlet_name, dd.cashier_id as user_id,
                         coalesce(u.full_name, 'Unknown') as name, count(*) as bills, sum(dd.discount_total) as total, max(dd.pct) as max_pct
                    from d dd
                    left join public.branches b on b.id = dd.branch_id
                    left join public.users u on u.id = dd.cashier_id
                   where dd.cashier_id is not null
                   group by dd.branch_id, b.name, dd.cashier_id, u.full_name) x), '[]'::jsonb),
      'by_day', coalesce((
          select jsonb_agg(jsonb_build_object('business_date', x.business_date, 'bills', x.bills, 'total', x.total, 'max_pct', x.max_pct)
                           order by x.business_date)
            from (select dd.business_date, count(*) as bills, sum(dd.discount_total) as total, max(dd.pct) as max_pct
                    from d dd group by dd.business_date) x), '[]'::jsonb),
      'by_outlet', coalesce((
          select jsonb_agg(jsonb_build_object('branch_id', x.branch_id, 'outlet_name', x.outlet_name, 'bills', x.bills,
                   'total', x.total, 'max_pct', x.max_pct) order by x.total desc, x.outlet_name)
            from (select dd.branch_id, coalesce(b.name, 'Unknown outlet') as outlet_name, count(*) as bills,
                         sum(dd.discount_total) as total, max(dd.pct) as max_pct
                    from d dd left join public.branches b on b.id = dd.branch_id
                   group by dd.branch_id, b.name) x), '[]'::jsonb)));
end $$;

