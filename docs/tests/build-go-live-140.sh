#!/usr/bin/env bash
# Regenerates docs/go-live-140.sql from supabase/migrations/140_*.sql (run it again after any edit to the migration).
set -eu
cd "$(dirname "$0")/../.."
M=supabase/migrations/140_bulk_price_range_offline_open_price_summary_extras.sql
[ -f "$M" ] || { echo "missing $M"; exit 1; }
grep -q 'mig140' "$M" && { echo "migration must not contain the tag mig140"; exit 1; }
{
cat <<'HEAD'
-- GO-LIVE 140: three money-safety fixes.
--   (1) bulk price change: a new price below zero (or above 10000000) is flagged in the preview and the whole batch is refused on apply
--   (2) sync_offline_bill: open-priced items are re-checked when an offline bill is sent (price above zero; a user without
--       order.open_price gets the bill recorded and flagged for review, never lost)
--   (3) daily summary (app.report_summary): adds guests (covers), sales per guest and tips (memo) to the figures
--
-- Paste this WHOLE file into the Supabase SQL editor and press Run. It is all-or-nothing: if anything fails,
-- nothing is changed (a DO block is one transaction).
--
--   * It refuses to run unless migration 139 (139_erase_groups_tips_and_price_changes) is already recorded in supabase_migrations.schema_migrations.
--   * It refuses to run if 140 is already recorded (so a second run changes nothing and says so).
--   * It runs the text of supabase/migrations/140_bulk_price_range_offline_open_price_summary_extras.sql (create or replace functions only;
--     no table, column or data is touched), then records version/name in supabase_migrations.schema_migrations like the other migrations.
--
-- Generated by docs/tests/build-go-live-140.sh - do not edit by hand.
do $go$
begin
  if not exists (select 1 from supabase_migrations.schema_migrations
                  where name like '139\_%' or name like '%erase\_groups\_tips\_and\_price\_changes%') then
    raise exception 'GO-LIVE 140 STOPPED: change 139 (erase_groups_tips_and_price_changes) is not recorded as applied. Apply 130-139 first. Nothing was changed.';
  end if;
  if exists (select 1 from supabase_migrations.schema_migrations
              where name like '140\_%' or name like '%bulk\_price\_range\_offline\_open\_price%') then
    raise exception 'GO-LIVE 140 STOPPED: change 140 (bulk_price_range_offline_open_price_summary_extras) is already recorded as applied. Nothing was changed.';
  end if;

  execute $mig140$
HEAD
cat "$M"
cat <<'TAIL'

$mig140$;

  insert into supabase_migrations.schema_migrations (version, name)
  values (to_char(clock_timestamp() at time zone 'utc', 'YYYYMMDDHH24MISS'), '140_bulk_price_range_offline_open_price_summary_extras');

  raise notice 'GO-LIVE 140 done: bulk price range check, offline open-price re-check (sync_offline_bill) and guests/tips in the daily summary are installed.';
end
$go$;
TAIL
} > docs/go-live-140.sql
echo "wrote docs/go-live-140.sql"
