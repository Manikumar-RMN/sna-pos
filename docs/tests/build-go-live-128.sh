#!/usr/bin/env bash
# Regenerates docs/go-live-128.sql from supabase/migrations/128_report_pack_rpcs.sql (run it again after any edit to the migration).
set -eu
cd "$(dirname "$0")/../.."
M=supabase/migrations/128_report_pack_rpcs.sql
grep -q 'mig128' "$M" && { echo "migration must not contain the tag mig128"; exit 1; }
{
cat <<'HEAD'
-- GO-LIVE 128: report pack RPCs (popular items, unsold/slow items, waiter-wise sales, discount summary).
--
-- Paste this WHOLE file into the Supabase SQL editor and press Run. It is all-or-nothing: if anything fails,
-- nothing is changed (a DO block is one transaction).
--
--   * It refuses to run unless migration 127 is already recorded in supabase_migrations.schema_migrations.
--   * It refuses to run if 128 is already recorded (so a second run changes nothing and says so).
--   * It runs the text of supabase/migrations/128_report_pack_rpcs.sql (create or replace functions only; no table or data
--     is touched), then records version/name in supabase_migrations.schema_migrations like the other migrations.
--
-- Generated by docs/tests/build-go-live-128.sh - do not edit by hand.
do $go$
begin
  if not exists (select 1 from supabase_migrations.schema_migrations
                  where name like '127\_%' or name like '%login\_staff\_no\_lock\_leak%') then
    raise exception 'GO-LIVE 128 STOPPED: change 127 (login_staff_no_lock_leak) is not recorded as applied. Apply 127 first. Nothing was changed.';
  end if;
  if exists (select 1 from supabase_migrations.schema_migrations
              where name like '128\_%' or name like '%report\_pack\_rpcs%') then
    raise exception 'GO-LIVE 128 STOPPED: change 128 (report_pack_rpcs) is already recorded as applied. Nothing was changed.';
  end if;

  execute $mig128$
HEAD
cat "$M"
cat <<'TAIL'

$mig128$;

  insert into supabase_migrations.schema_migrations (version, name)
  values (to_char(clock_timestamp() at time zone 'utc', 'YYYYMMDDHH24MISS'), '128_report_pack_rpcs');

  raise notice 'GO-LIVE 128 done: report_popular_items, report_unsold_items, report_waiter_sales, report_discounts are installed.';
end
$go$;
TAIL
} > docs/go-live-128.sql
echo "wrote docs/go-live-128.sql"
