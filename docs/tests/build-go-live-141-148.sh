#!/usr/bin/env bash
# Regenerates docs/go-live-141-148.sql from every supabase/migrations/14[1-8]_*.sql that exists (run it again after any edit to those migrations, and
# again after 143 / 144 are merged: the integrator rebuilds it with all eight). One all-or-nothing DO block: guards, then each migration executed with its own
# dollar-quote tag, then each recorded in supabase_migrations.schema_migrations.
set -eu
cd "$(dirname "$0")/../.."
FILES=$(ls supabase/migrations/14[1-8]_*.sql 2>/dev/null | LC_ALL=C sort || true)
[ -n "$FILES" ] || { echo "no supabase/migrations/14[1-8]_*.sql found"; exit 1; }
NAMES=""; SUMMARY=""; NUMS=""
for f in $FILES; do
  n="$(basename "$f" .sql)"; num="${n%%_*}"
  grep -q "mig$num\\\$" "$f" && { echo "$n contains the go-live dollar-quote tag mig$num"; exit 1; }
  NAMES="$NAMES'$n',"; NUMS="$NUMS $num"
  SUMMARY="$SUMMARY--   $(head -1 "$f" | sed -E 's/^-- *//' | cut -c1-150)"$'\n'
done
NAMES="${NAMES%,}"; NUMS="${NUMS# }"
HAVE143=no; ls supabase/migrations/143_*.sql >/dev/null 2>&1 && HAVE143=yes
{
cat <<HEAD
-- GO-LIVE 141-148: the third batch ($NUMS), in one go.
$SUMMARY--
-- Paste this WHOLE file into the Supabase SQL editor and press Run. It is all-or-nothing: if anything fails,
-- nothing is changed (a DO block is one transaction).
--
--   * It refuses to run unless migration 140 (140_bulk_price_range_offline_open_price_summary_extras) is recorded in supabase_migrations.schema_migrations.
--   * It refuses to run if ANY of these names is already recorded (some of the migrations create tables, so a second run is refused and changes nothing).
--   * Each migration's text is executed on its own (its own dollar-quote tag), then recorded with its own version and name (consecutive versions).
--   * Migration 148 stops the whole run when the stock-count tables of 143 do not exist (143 must be in this file or already applied).
--
-- Generated by docs/tests/build-go-live-141-148.sh - do not edit by hand.
do \$go\$
declare
  v_base timestamp := (clock_timestamp() at time zone 'utc')::timestamp(0);
  v_names text[] := array[$NAMES];
  v_done text;
begin
  if not exists (select 1 from supabase_migrations.schema_migrations
                  where name = '140_bulk_price_range_offline_open_price_summary_extras' or name like '140\\_bulk\\_price\\_range%') then
    raise exception 'GO-LIVE 141-148 STOPPED: change 140 (bulk_price_range_offline_open_price_summary_extras) is not recorded as applied. Apply 140 first. Nothing was changed.';
  end if;
  select string_agg(name, ', ' order by name) into v_done from supabase_migrations.schema_migrations where name = any (v_names);
  if v_done is not null then
    raise exception 'GO-LIVE 141-148 STOPPED: already recorded as applied: %. Nothing was changed.', v_done;
  end if;
HEAD
i=0
for f in $FILES; do
  n="$(basename "$f" .sql)"; num="${n%%_*}"
  printf '\n  -- ---------------------------------------------------------------- %s\n  execute $mig%s$\n' "$n" "$num"
  cat "$f"
  printf '\n$mig%s$;\n  insert into supabase_migrations.schema_migrations (version, name)\n  values (to_char(v_base + interval '"'"'%s second'"'"', '"'"'YYYYMMDDHH24MISS'"'"'), '"'"'%s'"'"');\n' "$num" "$i" "$n"
  i=$((i+1))
done
cat <<TAIL

  raise notice 'GO-LIVE 141-148 done: $NUMS installed and recorded.';
end
\$go\$;
TAIL
} > docs/go-live-141-148.sql
echo "wrote docs/go-live-141-148.sql ($NUMS)"
