#!/usr/bin/env bash
# Regenerates docs/go-live-129.sql from supabase/migrations/129_report_pack_2_rpcs.sql (run it again after any edit to the migration).
set -eu
cd "$(dirname "$0")/../.."
M=supabase/migrations/129_report_pack_2_rpcs.sql
grep -q 'mig129' "$M" && { echo "migration must not contain the tag mig129"; exit 1; }
{
cat <<'HEAD'
-- GO-LIVE 129: report pack 2 RPCs (pending KOT, pending bills, bill-wise detail, void bills, settlement, sales day book, sales month book, tax report).
--
-- Paste this WHOLE file into the Supabase SQL editor and press Run. It is all-or-nothing: if anything fails,
-- nothing is changed (a DO block is one transaction).
--
--   * It refuses to run unless migration 128 is already recorded in supabase_migrations.schema_migrations.
--   * It refuses to run if 129 is already recorded (so a second run changes nothing and says so).
--   * It runs the text of supabase/migrations/129_report_pack_2_rpcs.sql (create or replace functions only; no table or data
--     is touched), then records version/name in supabase_migrations.schema_migrations like the other migrations.
--
-- Generated by docs/tests/build-go-live-129.sh - do not edit by hand.
do $go$
begin
  if not exists (select 1 from supabase_migrations.schema_migrations
                  where name like '128\_%' or name like '%report\_pack\_rpcs%') then
    raise exception 'GO-LIVE 129 STOPPED: change 128 (report_pack_rpcs) is not recorded as applied. Apply 128 first. Nothing was changed.';
  end if;
  if exists (select 1 from supabase_migrations.schema_migrations
              where name like '129\_%' or name like '%report\_pack\_2\_rpcs%') then
    raise exception 'GO-LIVE 129 STOPPED: change 129 (report_pack_2_rpcs) is already recorded as applied. Nothing was changed.';
  end if;

  execute $mig129$
HEAD
cat "$M"
cat <<'TAIL'

$mig129$;

  insert into supabase_migrations.schema_migrations (version, name)
  values (to_char(clock_timestamp() at time zone 'utc', 'YYYYMMDDHH24MISS'), '129_report_pack_2_rpcs');

  raise notice 'GO-LIVE 129 done: report_pending_kot, report_pending_bills, report_bills_detail, report_void_bills, report_settlement, report_sales_day_book, report_sales_month_book, report_tax are installed.';
end
$go$;
TAIL
} > docs/go-live-129.sql
echo "wrote docs/go-live-129.sql"
