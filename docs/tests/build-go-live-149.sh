#!/usr/bin/env bash
# Regenerates docs/go-live-149.sql from supabase/migrations/149_floor_status_billed.sql (run it again after any edit to the migration).
set -eu
cd "$(dirname "$0")/../.."
M=supabase/migrations/149_floor_status_billed.sql
[ -f "$M" ] || { echo "missing $M"; exit 1; }
grep -q 'mig149' "$M" && { echo "migration must not contain the tag mig149"; exit 1; }
{
cat <<'HEAD'
-- GO-LIVE 149: blue "bill printed" table colour data.
--   floor_status() (the table-colour feed of the floor screen) gets two new LAST columns:
--     billed_bills = how many of the table's open bills have a bill.print / bill.reprint audit row (the bill was printed)
--     billed_at    = when the oldest of those prints was logged
--   White = free, blue = bill printed and payment pending; after payment the table is white again. Every old column keeps its
--   name, type, order and filter. Read only: no table, column or data is touched.
--
-- Paste this WHOLE file into the Supabase SQL editor and press Run. It is all-or-nothing: if anything fails,
-- nothing is changed (a DO block is one transaction).
--
--   * It refuses to run unless migration 148 (148_erase_groups_and_grants) is already recorded in supabase_migrations.schema_migrations.
--   * It refuses to run if 149 is already recorded (so a second run changes nothing and says so).
--   * It runs the text of supabase/migrations/149_floor_status_billed.sql (drop + create of the function public.floor_status() only),
--     then records version/name in supabase_migrations.schema_migrations like the other migrations.
--
-- Generated by docs/tests/build-go-live-149.sh - do not edit by hand.
do $go$
begin
  if not exists (select 1 from supabase_migrations.schema_migrations
                  where name like '148\_%' or name like '%erase\_groups\_and\_grants%') then
    raise exception 'GO-LIVE 149 STOPPED: change 148 (erase_groups_and_grants) is not recorded as applied. Apply 141-148 first. Nothing was changed.';
  end if;
  if exists (select 1 from supabase_migrations.schema_migrations
              where name like '149\_%' or name like '%floor\_status\_billed%') then
    raise exception 'GO-LIVE 149 STOPPED: change 149 (floor_status_billed) is already recorded as applied. Nothing was changed.';
  end if;

  execute $mig149$
HEAD
cat "$M"
cat <<'TAIL'

$mig149$;

  insert into supabase_migrations.schema_migrations (version, name)
  values (to_char(clock_timestamp() at time zone 'utc', 'YYYYMMDDHH24MISS'), '149_floor_status_billed');

  raise notice 'GO-LIVE 149 done: floor_status() now also returns billed_bills and billed_at (blue "bill printed" table colour).';
end
$go$;
TAIL
} > docs/go-live-149.sql
echo "wrote docs/go-live-149.sql"
