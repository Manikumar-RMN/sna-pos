#!/usr/bin/env bash
# Regenerates docs/go-live-130-139.sql from supabase/migrations/130..139 (run it again after any edit to those migrations).
# One all-or-nothing DO block: guards, then each migration executed with its own dollar-quote tag, then each recorded.
set -eu
cd "$(dirname "$0")/../.."
LIST="130_tax_rate_schedule 131_open_price_and_business_date_tax 132_move_order_items 133_order_tips 134_floor_status 135_log_print_reprint_audit 136_bulk_price_change 137_copy_rights_and_access 138_report_pack_3_covers_reprints_tips 139_erase_groups_tips_and_price_changes"
for n in $LIST; do
  [ -f "supabase/migrations/$n.sql" ] || { echo "missing supabase/migrations/$n.sql"; exit 1; }
  grep -q 'mig1[0-9][0-9]\$' "supabase/migrations/$n.sql" && { echo "$n contains a go-live dollar-quote tag"; exit 1; }
done
NAMES=""; for n in $LIST; do NAMES="$NAMES'$n',"; done; NAMES="${NAMES%,}"
{
cat <<HEAD
-- GO-LIVE 130-139: the "one-batch" change set, ten migrations in one go.
--   130 tax rate schedule (a new tax rate can start on a future date)
--   131 open-priced items (products.is_open_price, order_items.open_price, right order.open_price) + tax rate by business day
--   132 move_order_items (move one item to another table)
--   133 order_tips (tips as a memo) + pay_order with p_tip
--   134 floor_status (table colours)
--   135 log_print (print and reprint audit; order.reprint is now enforced)
--   136 bulk price change (price_change_batches, price_change_lines, preview / apply / undo)
--   137 copy_role_rights, copy_staff_access
--   138 report pack 3 (covers, reprints, tips) + corrected pending KOT / pending bills
--   139 erase_groups knows the new tables
--
-- Paste this WHOLE file into the Supabase SQL editor and press Run. It is all-or-nothing: if anything fails,
-- nothing is changed (a DO block is one transaction).
--
--   * It refuses to run unless migration 129 (129_report_pack_2_rpcs) is recorded in supabase_migrations.schema_migrations.
--   * It refuses to run if ANY of the ten names is already recorded. Migrations 133 and 136 create tables and are not
--     re-runnable, so a second run of this file is refused and changes nothing.
--   * Each migration's text is executed on its own (its own dollar-quote tag), then recorded with its own version and name
--     (consecutive versions, distinct), like the other migrations.
--
-- Generated by docs/tests/build-go-live-130-139.sh - do not edit by hand.
do \$go\$
declare
  v_base timestamp := (clock_timestamp() at time zone 'utc')::timestamp(0);
  v_names text[] := array[$NAMES];
  v_done text;
begin
  if not exists (select 1 from supabase_migrations.schema_migrations
                  where name = '129_report_pack_2_rpcs' or name like '129\\_report\\_pack\\_2%') then
    raise exception 'GO-LIVE 130-139 STOPPED: change 129 (report_pack_2_rpcs) is not recorded as applied. Apply 129 first. Nothing was changed.';
  end if;
  select string_agg(name, ', ' order by name) into v_done from supabase_migrations.schema_migrations where name = any (v_names);
  if v_done is not null then
    raise exception 'GO-LIVE 130-139 STOPPED: already recorded as applied: %. Nothing was changed.', v_done;
  end if;
HEAD
i=0
for n in $LIST; do
  num="${n%%_*}"
  printf '\n  -- ---------------------------------------------------------------- %s\n  execute $mig%s$\n' "$n" "$num"
  cat "supabase/migrations/$n.sql"
  printf '\n$mig%s$;\n  insert into supabase_migrations.schema_migrations (version, name)\n  values (to_char(v_base + interval '"'"'%s second'"'"', '"'"'YYYYMMDDHH24MISS'"'"'), '"'"'%s'"'"');\n' "$num" "$i" "$n"
  i=$((i+1))
done
cat <<'TAIL'

  raise notice 'GO-LIVE 130-139 done: ten changes installed and recorded (130 tax schedule, 131 open price, 132 move item, 133 tips, 134 floor status, 135 print log, 136 bulk price, 137 copy rights, 138 reports, 139 erase lists).';
end
$go$;
TAIL
} > docs/go-live-130-139.sql
echo "wrote docs/go-live-130-139.sql"
